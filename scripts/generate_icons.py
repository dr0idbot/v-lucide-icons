def resolve_version(explicit: str | None) -> str:
    """Return the requested version or the latest stable release."""
    if explicit:
        return explicit
    with urllib.request.urlopen(f"{NPM_REGISTRY}/{NPM_PACKAGE}") as response:
        metadata = json.loads(response.read())
    stable = [
        version
        for version in metadata["versions"]
        if re.fullmatch(r"\d+\.\d+\.\d+", version)
    ]
    if not stable:
        raise SystemExit(f"No stable versions found for {NPM_PACKAGE}")
    return max(stable, key=lambda v: tuple(map(int, v.split("."))))


def fetch_tarball(version: str) -> tarfile.TarFile:
    url = TARBALL_URL.format(version=version)
    print(f"Fetching {url}")
    with urllib.request.urlopen(url) as response:
        payload = response.read()
    print(f"Downloaded {len(payload):,} bytes")
    return tarfile.open(fileobj=io.BytesIO(payload))


def extract_package(tarball: tarfile.TarFile) -> tuple[dict[str, str], str]:
    """Return ({icon filename stem: normalized svg}, LICENSE text)."""
    prefix = "package/icons/"
    icons: dict[str, str] = {}
    license_text: str | None = None
    for member in tarball.getmembers():
        name = member.name
        if name == "package/LICENSE":
            license_text = tarball.extractfile(member).read().decode("utf-8")
        elif name.startswith(prefix) and name.endswith(".svg") and member.isfile():
            stem = name[len(prefix):-len(".svg")]
            if not re.fullmatch(r"[a-z0-9-]+", stem):
                raise SystemExit(f"Unexpected icon file name: {name}")
            svg = tarball.extractfile(member).read().decode("utf-8")
            icons[stem] = normalize_svg(svg)
    if license_text is None:
        raise SystemExit("LICENSE not found in npm tarball")
    return icons, license_text


def normalize_svg(svg: str) -> str:
    """Strip the license comment, XML declaration, and width/height."""
    svg = XML_DECL_RE.sub("", svg)
    svg = COMMENT_RE.sub("", svg)
    svg = WIDTH_HEIGHT_RE.sub("", svg)
    svg = svg.replace("\r\n", "\n").replace("\r", "\n")
    if not svg.endswith("\n"):
        svg += "\n"
    return svg


def to_constant(icon_name: str, reserved: frozenset[str]) -> str:
    """Convert a kebab-case icon name to a Java constant name."""
    if not re.fullmatch(r"[a-z0-9-]+", icon_name):
        raise SystemExit(f"Invalid icon name: {icon_name!r}")
    constant = icon_name.replace("-", "_").upper()
    if constant[0].isdigit():
        constant = "_" + constant
    if constant in reserved:
        raise SystemExit(f"Icon {icon_name!r} maps to reserved word {constant!r}")
    return constant


def write_svgs(icons: dict[str, str]) -> list[tuple[str, str, str]]:
    """Ensure the SVG directory matches upstream exactly."""
    SVG_DIR.mkdir(parents=True, exist_ok=True)
    existing = {path.stem for path in SVG_DIR.glob("*.svg")}
    changes: list[tuple[str, str, str]] = []
    for stem, svg in sorted(icons.items()):
        path = SVG_DIR / f"{stem}.svg"
        if path.exists():
            current = path.read_text(encoding="utf-8")
            if current == svg:
                continue
            changes.append(("M", stem, ""))
        else:
            changes.append(("A", stem, ""))
        path.write_text(svg, encoding="utf-8", newline="")  # force LF
    for stem in sorted(existing - icons.keys()):
        (SVG_DIR / f"{stem}.svg").unlink()
        changes.append(("D", stem, ""))
    return changes


def generate_enum(icons: dict[str, str], version: str) -> None:
    names = sorted(icons)
    lines = []
    for index, stem in enumerate(names):
        term = ";" if index == len(names) - 1 else ","
        constant = to_constant(stem, JAVA_RESERVED_WORDS)
        lines.append(f'    {constant}("{stem}"){term}\n')
    header = ENUM_HEADER.replace("@@VERSION@@", version)
    ENUM_FILE.write_text(
        header + "\n".join(lines) + "\n" + ENUM_FOOTER,
        encoding="utf-8",
        newline="",
    )


def generate_notice(license_text: str, version: str, count: int) -> None:
    notice = (
        NOTICE_HEADER.replace("@@ICON_COUNT@@", str(count))
        .replace("@@VERSION@@", version)
        + license_text
        + NOTICE_FOOTER
    )
    NOTICE_FILE.write_text(notice, encoding="utf-8", newline="")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--version",
        help="exact lucide-static version to generate from (default: latest stable)",
    )
    args = parser.parse_args()

    version = resolve_version(args.version)
    with fetch_tarball(version) as tarball:
        icons, license_text = extract_package(tarball)

    changes = write_svgs(icons)
    generate_enum(icons, version)
    generate_notice(license_text, version, len(icons))

    added = sum(1 for c in changes if c[0] == "A")
    modified = sum(1 for c in changes if c[0] == "M")
    removed = sum(1 for c in changes if c[0] == "D")
    print(f"Lucide {version}: {len(icons)} icons")
    print(f"SVGs: {added} added, {modified} modified, {removed} removed")
    print(f"Enum: {ENUM_FILE.relative_to(PROJECT_ROOT)} ({len(icons)} constants)")
    print(f"Notice: {NOTICE_FILE.relative_to(PROJECT_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
