#!/usr/bin/env python3
"""Lucide icon generator for v-lucide-icons.

Maintainer-only tool that rewrites the icon set from an exact version of the
upstream ``lucide-static`` npm package:

1. Downloads the versioned npm tarball from registry.npmjs.org (in memory).
2. Extracts ``icons/*.svg``, normalizes them, and writes them to
   ``src/main/resources/META-INF/resources/lucide/`` (stale files removed).
3. Reproduces ``NOTICE`` with the upstream LICENSE embedded verbatim.
4. Regenerates ``src/main/java/io/github/dr0idbot/vlucide/LucideIcon.java``.

Requires only the Python 3.10+ standard library. Generated files stay
committed in Git; downstream builds need no Python, Node, or network.

Usage:
    python3 scripts/generate_icons.py                # latest stable release
    python3 scripts/generate_icons.py --version 1.41.0
"""

from __future__ import annotations

import argparse
import io
import json
import re
import sys
import tarfile
import urllib.request
from pathlib import Path

NPM_PACKAGE = "lucide-static"
NPM_REGISTRY = "https://registry.npmjs.org"
TARBALL_URL = f"{NPM_REGISTRY}/{NPM_PACKAGE}/-/{NPM_PACKAGE}-{{version}}.tgz"

PROJECT_ROOT = Path(__file__).resolve().parent.parent
SVG_DIR = PROJECT_ROOT / "src/main/resources/META-INF/resources/lucide"
ENUM_FILE = PROJECT_ROOT / "src/main/java/io/github/dr0idbot/vlucide/LucideIcon.java"
NOTICE_FILE = PROJECT_ROOT / "NOTICE"

JAVA_RESERVED_WORDS = frozenset("""
abstract assert boolean break byte case catch char class const continue
default do double else enum exports extends false final finally float for
goto if implements import instanceof int interface long module native new
non-sealed null open opens package permit private protected provides public
record requires return restricted sealed short static strictfp super switch
synchronized this throw throws to transient transitive true try uses var
void volatile while with yield
""".split())  # a dash cannot survive name conversion; kept for completeness

# Normalization: drop the upstream @license comment, the optional XML
# declaration, and the root width/height attributes. Keep everything else
# byte-for-byte from upstream (except line ending normalization).
XML_DECL_RE = re.compile(r"^\s*<\?xml[^?]*\?>\s*\n")
COMMENT_RE = re.compile(r"<!--.*?-->\s*\n", re.DOTALL)
WIDTH_HEIGHT_RE = re.compile(r'^\s*width="[^"]*"\n^\s*height="[^"]*"\n', re.MULTILINE)

